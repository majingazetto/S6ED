    WRN = range(10, 18)         # "Unsaved changes!" at char col 20
    LINES = ['%02d QUIT DIALOG TEST LINE' % i for i in range(10)]
    variants = ('clean', 'dirty')

    def fixture(self, ctx, variant=None):
        return crlf(self.LINES)

