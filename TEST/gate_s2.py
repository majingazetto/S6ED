# --- S2-6  BACKSPACE, THEN KEEP TYPING --------------------------------


class S26DelType(S2Case):
    name = 'S2-6-deltype'
    desc = 'typing still works after BACKSPACE and after DEL'
    origin = ('round 3: EDDELBK and EDDELCHR ran their shift loop to a hard '
               '79 and blanked WORKBUF + 80.  On a 1+64+64 record that drags '
               'the attribute byte of column 0 into the LAST TEXT COLUMN, '
               'after which EDINSCHR sees a full record and refuses every '
               'keystroke on that line -- silently, in WRAP_DEV.  LINEWRT '
               'persists it, so the line stays poisoned.')
    LINES = ['HELLO MSX WORLD', 'SECOND LINE']
    # Both delete keys and both wrap modes.  The mode matters: in WRAP_DEV the
    # refused insert is a mute RET NZ -- the user's "it just stops typing" --
    # while in WRAP_TXT it goes to EDPSHWR and shows up as a spurious wrap
    # instead, which is why TOTLINES is asserted as well as the text.
    variants = ('bs-dev', 'del-dev', 'bs-txt', 'del-txt')

    def fixture(self, ctx, variant=None):
        return crlf(self.LINES)

    def config(self, ctx, variant=None):
        mode = 'DEV' if variant.endswith('-dev') else 'TXT'
        return self.cfg.replace('WRAP=TXT', 'WRAP=' + mode)

    def timeline(self, ctx, variant=None):
        t = Timeline()
        for k in 'LABEL':
            t.press(k)
        t.snap('typed')
        t.press('BS' if variant.startswith('bs') else 'DEL', repeat=3)
        t.snap('deleted')
        t.press('X')
        t.press('S', mods=['CTRL'])
        t.wait(3.0)
        t.snap('saved', vram='pat')
        return t

    def verify(self, ctx, runs):
        checks = []
        for variant, run in sorted(runs.items()):
            # keymatrixdown without SHIFT delivers lowercase.
            head = self.LINES[0]
            if variant.startswith('bs'):
                want_first = 'la' + 'x' + head       # 5 typed, 3 removed
            else:
                want_first = 'label' + 'x' + head[3:]  # DEL eats 3 ahead
            typed = run.var('typed', 'CURX')
            checks.append(Check('S2-6/%s/typed' % variant, typed == 5,
                                'CURX = %s after typing LABEL' % typed))
            got = run.session.extract(run.dsk, 'DOC.TXT')
            first = (got or b'').split(b'\r\n')[0].decode('ascii', 'replace')
            tot = run.var('saved', 'TOTLINES')
            checks.append(Check('S2-6/%s/totlines' % variant,
                                tot == len(self.LINES),
                                'TOTLINES = %s (expected %d: nothing wrapped)'
                                % (tot, len(self.LINES))))
            checks.append(Check('S2-6/%s/line' % variant, first == want_first,
                                'line reads %r' % first if first == want_first
                                else 'line reads %r, expected %r'
                                     % (first, want_first)))
            pat = run.blob('saved', 'pat')
            if pat is not None:
                lines = [want_first] + self.LINES[1:]
                bad = pattern.mismatched_rows(
                    pat, font(ctx), lines, run.var('saved', 'TOPLINE'),
                    cursor=(pattern.TXRFIRST + run.var('saved', 'CURY'),
                            run.var('saved', 'CURX')))
                checks.append(Check('S2-6/%s/screen' % variant, not bad,
                                    'screen agrees with the document'
                                    if not bad else 'rows differ: %s' % bad[:4]))
        return checks


# --- S2-7  ENTER ON THE LAST VISIBLE ROW ------------------------------


class S27EnterBot(S2Case):
    name = 'S2-7-enterbot'
    desc = 'splitting on the last visible row repaints the head, not the status bar'
    origin = ('round 3: EDNWLIN repainted the shortened head with a literal '
               'LD B, 23 -- the row below the last visible one on S2, which '
               'is the STATUS BAR.  The head at row 21 was left stale and the '
               'status bar was painted over with document text.')
    LINES = ['LINE %03d ABCDEFGHIJ' % i for i in range(40)]

    def fixture(self, ctx, variant=None):
        return crlf(self.LINES)

    def timeline(self, ctx, variant=None):
        t = Timeline()
        t.press('DOWN', repeat=25)          # well past the bottom of the band
        t.press('RIGHT', repeat=4)          # split mid-line
        t.snap('atbottom', vram='patcol')
        t.press('RETURN')
        t.snap('split', vram='patcol')
        t.press('S', mods=['CTRL'])
        t.wait(3.0)
        t.snap('saved')
        return t

    def verify(self, ctx, runs):
        run = one(runs)
        before = run.blob('atbottom', 'patcol')
        after = run.blob('split', 'patcol')
        if before is None or after is None:
            return [Check('S2-7/dump', False, 'missing VRAM dump')]
        checks = [
            Check('S2-7/at-band-bottom',
                  run.var('atbottom', 'CURY') == pattern.ROWSVIS - 1,
                  'CURY = %s before the split'
                  % run.var('atbottom', 'CURY')),
            Check('S2-7/totlines',
                  run.var('split', 'TOTLINES') == len(self.LINES) + 1,
                  'TOTLINES = %s (expected %d)'
                  % (run.var('split', 'TOTLINES'), len(self.LINES) + 1)),
        ]
        # The status bar is chrome.  It may legitimately change (the modified
        # marker), but it must still be CHROME: with LD B, 23 the split
        # painted a document line there, in COLTXT.  Since the chrome split
        # the bar has its own role, VCOLSTAT, distinct from the menu bar's.
        _, colours = pattern.uniform_colour_cells(after[0x2000:],
                                                  pattern.STBROW)
        checks.append(Check(
            'S2-7/status-is-chrome', colours == {pattern.COLSTAT},
            'the status bar is still painted in COLSTAT (#%02X)'
            % pattern.COLSTAT if colours == {pattern.COLSTAT} else
            'status bar colours: %s' % sorted('#%02X' % c for c in colours)))
        head_row = pattern.row_of(after[:0x2000], pattern.STBROW)
        band_row = pattern.row_of(after[:0x2000], pattern.TXRLAST)
        checks.append(Check(
            'S2-7/status-not-text', head_row != band_row,
            'the status bar does not carry a copy of a document row'))
        # And the whole band must agree with the document that was saved.
        got = run.session.extract(run.dsk, 'DOC.TXT')
        lines = (got or b'').decode('ascii', 'replace').split('\r\n')
        while lines and lines[-1] == '':
            lines.pop()
        bad = pattern.mismatched_rows(
            after[:0x2000], font(ctx), lines, run.var('split', 'TOPLINE'),
            cursor=(pattern.TXRFIRST + run.var('split', 'CURY'),
                    run.var('split', 'CURX')))
        checks.append(Check('S2-7/head-repainted', not bad,
                            'every band row agrees with the saved document'
                            if not bad else 'rows differ: %s' % bad[:6]))
        return checks


# --- S2-8  DIFFERENTIAL PAINTERS AGREE WITH A FULL REDRAW -------------


class S28RenderPure(S2Case):
    name = 'S2-8-renderpure'
    desc = 'after a burst of edits the screen equals a full REDRAW of the document'
    origin = ('the G7 idea, which is the one general case in the S6 gate: a '
               'REDRAW repaints from the document alone, so forcing one and '
               'diffing tests every differential painter at once.  Here it is '
               'checked BOTH ways -- against the REDRAW and against the '
               'computed table -- so a renderer that is consistently wrong '
               'still fails.')
    LINES = ['ROW %03d %s' % (i, 'abcdefghijklmnop') for i in range(30)]

    def fixture(self, ctx, variant=None):
        return crlf(self.LINES)

    # The edits end with a SPLIT, deliberately.  The first version ended with
    # BACKSPACE at column 0, which in WRAP_TXT cascades REFLOW and finishes
    # with a full REDRAW -- repainting the whole screen microseconds before
    # the sample and blinding the case: a mutation that dropped SHIFTDNN's
    # VRAM push went clean through it.  A mid-document Enter uses SHIFTDN and
    # two RENDEROW calls and repaints nothing else, so whatever those leave
    # behind is still on screen when 'edited' is taken.
    def timeline(self, ctx, variant=None):
        t = Timeline()
        t.press('DOWN', repeat=3)
        t.press('RIGHT', repeat=5)
        for k in 'ZZ':
            t.press(k)                  # in-line insert  -> RENDIFF
        t.press('BS')                   # in-line delete  -> RENDIFF
        t.press('DEL', repeat=2)
        t.press('DOWN', repeat=2)
        t.press('RIGHT', repeat=4)
        t.press('RETURN')               # mid-document split -> SHIFTDN
        t.press('S', mods=['CTRL'])
        t.wait(3.0)
