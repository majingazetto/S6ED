        t.snap('dlg_no', vram='patcol', at='WINPOLL')
        t.press('LEFT')
        t.snap('dlg_yes', vram='patcol', at='WINPOLL')
        t.press('ESC')                          # cancel
        t.snap('after_esc', vram='patcol')
        t.press('ESC')                          # reopen
        t.snap('exit', at='TERM.TERMDON')       # armed before the key that quits
