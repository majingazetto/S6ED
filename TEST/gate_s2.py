"""Suite S2 -- the runtime gate for the SCREEN 2 / TMS9918 target.

Every case here is derived backwards from a defect that actually shipped, the
same rule the S6 gate follows.  Two things make this suite different:

  * It runs on an MSX1 (`Custom_MSX1_DOS2` under a Nextor kernel), so the VDP
    is the one the target is written for -- including the VRAM write pacing
    that silently drops bytes when it is wrong.
  * Its verdicts are taken against a pattern table COMPUTED in Python from
    `S2ED.FNT` and the document (see pattern.py), not against a captured
    image.  A golden image blesses whatever the renderer did on the day it was
    captured; the six defects of rounds 2 and 3 would all have passed that.

S2ED reserves two mapper segments, `DIRSEG` and `FTRSEG` -- and on S2 `FTRSEG`
is also the video shadow, so on the default machine there is nothing spare
(`SEGAVL = 0`), which is the point of using it.
"""

import pattern
from cases import Case, crlf
from harness import MACH_MSX1
from keys import Timeline
from result import Check

# The shipped defaults, minus the clock.  A case whose defect is a race must
# turn the clock off or the host RTC moves MAINLOOP's phase between runs and it
# passes and fails at random (learned on D8).
S2_CFG = """; generated by the S2ED test harness
PROFILE=STD
WRAP=TXT
MARKUP=OFF
CLOCK=0
TABWIDTH=4
EOL=AUTO
AUTOALIGN=OFF
"""


class S2Case(Case):
    machine = MACH_MSX1
    cfg = S2_CFG


def one(runs):
    return runs[None]


def font(ctx):
    return pattern.load_font(ctx)


def restored(after, before, currow, curcol):
    """Cells of `after` that do not match `before`, cursor blink forgiven.

    A modal window saves the region it covers and puts it back on close, so
    "the screen is what it was" is the check that catches a save or a restore
    off by one cell.  The one honest difference is the cursor: DRWCUR may have
    toggled its column between the two samples, so a cell that is exactly the
    inverse of that one column is not a difference.
    """
    bad = []
    for row in range(pattern.ROWS):
        acol = pattern.colour_row(after[0x2000:], row)
        bcol = pattern.colour_row(before[0x2000:], row)
        arow = pattern.row_of(after, row)
        brow = pattern.row_of(before, row)
        for cell in range(pattern.CELLS):
            sl = slice(cell * 8, (cell + 1) * 8)
            if acol[sl] != bcol[sl]:
                bad.append((row, cell))
                continue
            if arow[sl] == brow[sl]:
                continue
            if row == currow and curcol // 2 == cell:
                if arow[sl] == pattern.invert_column(brow, curcol)[sl]:
                    continue        # cursor blink phase
            bad.append((row, cell))
    return bad


def menubar(ctx):
    """The row 0 bar text, read from the source that paints it.

    The dropdown title spans live in .TITX in S2/MENU.Z8A and the bar text in
    .MNUTXT in S2/UI.Z8A.  Deriving the expected span from the bar means an
    edit to one without the other goes red instead of quietly highlighting
    the wrong four columns.
    """
    import re
    src = open(ctx.find_src_file('UI.Z8A'), errors='replace').read()
    m = re.search(r'\.MNUTXT\s+DEFM\s+"(.*)"', src)
    if not m:
        raise RuntimeError('.MNUTXT not found in S2/UI.Z8A')
    return m.group(1)


def titlespan(ctx, name):
    """(first column, width) of one menu title inside the row 0 bar."""
    col = menubar(ctx).index(name)
    return col, len(name)


# --- S2-1  THE SCREEN IS WHAT THE DOCUMENT SAYS -----------------------


class S21Render(S2Case):
    name = 'S2-1-render'
    desc = 'every painted row matches a pattern table computed from the font'
    origin = ('round 1: RENDEROW called COMROW with B destroyed by LINEREAD s '
               'LDIR, so every text row composed on top of row 0 and what '
               'reached the screen was whatever FTRSEG held there')
    LINES = ['%02d %s' % (i, 'ABCDEFGHIJKLMNOPQRSTUVWXYZ'[:1 + i % 26])
             for i in range(40)]

    def fixture(self, ctx, variant=None):
        return crlf(self.LINES)

    def timeline(self, ctx, variant=None):
        t = Timeline()
        t.snap('boot', vram='patcol')
        return t

    def verify(self, ctx, runs):
        run = one(runs)
        dump = run.blob('boot', 'patcol')
        checks = []
        if dump is None:
            return [Check('S2-1/dump', False, 'no VRAM dump')]
        pat, col = dump[:0x2000], dump[0x2000:]
        bad = pattern.mismatched_rows(
            pat, font(ctx), self.LINES, run.var('boot', 'TOPLINE'),
            cursor=(pattern.TXRFIRST + run.var('boot', 'CURY'),
                    run.var('boot', 'CURX')))
        checks.append(Check('S2-1/rows', not bad,
                            '%d text rows match the computed table'
                            % pattern.ROWSVIS if not bad else
                            'rows differ: %s' % bad[:6]))
        menu_pat = pattern.row_of(pat, pattern.MNUROW)
        want_menu = pattern.compose_row(font(ctx), menubar(ctx))
        dif_menu = pattern.differing_columns(menu_pat, want_menu)
        checks.append(Check('S2-1/menubar', not dif_menu,
                            'row 0 matches menubar text'
                            if not dif_menu else
                            'menubar cols differ: %s' % dif_menu[:6]))
        checks.append(Check('S2-1/totlines',
                            run.var('boot', 'TOTLINES') == len(self.LINES),
                            'TOTLINES = %s (expected %d)'
                            % (run.var('boot', 'TOTLINES'), len(self.LINES))))
        # FTRSEG is the video shadow as well as the feature container, so a
        # boot that did not claim both segments is a different bug wearing
        # this case's clothes.
        checks.append(Check('S2-1/segments', run.var('boot', 'SEGCNT') == 2,
                            'SEGCNT = %s (DIRSEG + FTRSEG)'
                            % run.var('boot', 'SEGCNT')))
        uniform, colours = pattern.uniform_colour_cells(col, pattern.TXRFIRST)
        checks.append(Check('S2-1/colour-expand', uniform == pattern.CELLS,
                            '%d/%d cells uniform across their 8 scanlines'
                            % (uniform, pattern.CELLS)))
        return checks


