# --- S2-3  THE CURSOR IS ONE COLUMN WIDE ------------------------------


class S23Cursor(S2Case):
    name = 'S2-3-cursor'
    desc = 'the cursor inverts exactly one text column'
    origin = ('round 2: the cursor swapped the FG/BG nibbles of the cell s '
               'colour byte.  Screen 2 colour addresses 8x1 SLICES and a cell '
               'holds two 4 px characters, so the finest thing a colour swap '
               'can invert is two columns.  PATINV inverts the pattern bits '
               'of the four pixel columns the text column owns instead.')
    LINES = ['CURSOR ON THIS LINE', 'SECOND LINE']

    def fixture(self, ctx, variant=None):
        return crlf(self.LINES)

    # The cursor blinks: MAINLOOP toggles BLNKPH every 20 JIFFY ticks (0.4 s
    # at 50 Hz), so a single sample can catch it drawn or erased and proves
    # nothing on its own.  Two rules make this deterministic:
    #
    #   * every sample is checked AGAINST ITS OWN BLNKPH -- erased must equal
    #     the plain render, drawn must equal it with one column inverted;
    #   * the sample intervals are deliberately uneven.  The first version
    #     spaced them evenly and every one landed in the same phase: a snap
    #     costs 0.6 s and the wait was 0.22 s, so BLNKCNT advanced 40-41 ticks
    #     between samples -- exactly two toggles.  Measured, all five read
    #     BLNKPH = 0 and the case failed against a cursor that was working.
    #
    # The last sample does not rely on the free-running blink at all: a
    # keystroke ends in .DRAWCUR, which draws the cursor and sets BLNKPH = 1,
    # so LEFT + RIGHT returns to the same column with the cursor guaranteed up.
    SAMPLES = 4

    def timeline(self, ctx, variant=None):
        t = Timeline()
        t.press('RIGHT', repeat=5)
        for i in range(self.SAMPLES):
            t.snap('s%d' % i, vram='pat')
            t.wait(0.1 * i)
        t.press('LEFT')
        # A short tail on purpose: .DRAWCUR runs just after key-down, and the
        # blink toggles 20 JIFFY ticks later.  The default 0.35 s tail puts
        # the sample 30 ticks after the keystroke -- past the toggle, cursor
        # already erased.  0.05 s puts it at ~15.
        t.press('RIGHT', tail=0.05)
        t.snap('drawn', vram='pat')
        return t

    def verify(self, ctx, runs):
        run = one(runs)
        curx = run.var('s0', 'CURX')
        row = pattern.TXRFIRST + (run.var('s0', 'CURY') or 0)
        plain = pattern.compose_row(font(ctx), self.LINES[0])
        inverted = pattern.invert_column(plain, curx)

        wrong, phases = [], []
        for label in ['s%d' % i for i in range(self.SAMPLES)] + ['drawn']:
            pat = run.blob(label, 'pat')
            if pat is None:
                wrong.append('%s: no dump' % label)
                continue
            got = pattern.row_of(pat, row)
            ph = run.var(label, 'BLNKPH')
            phases.append(ph)
            want = inverted if ph == 1 else plain
            cols = pattern.differing_columns(got, want)
            if cols:
                wrong.append('%s (BLNKPH=%s): columns %s' % (label, ph, cols))

        drawn = run.var('drawn', 'BLNKPH')
        got = run.blob('drawn', 'pat')
        one_col = (pattern.differing_columns(
            pattern.row_of(got, row), plain) == [curx]) if got else False
        return [
            Check('S2-3/curx', curx == 5, 'CURX = %s (expected 5)' % curx),
            Check('S2-3/blink-exact', not wrong,
                  'all %d samples match their own blink phase exactly '
                  '(phases seen: %s)' % (len(phases), phases)
                  if not wrong else '; '.join(wrong[:4])),
            Check('S2-3/drawn-up', drawn == 1,
                  'the cursor is up after a keystroke (BLNKPH = %s)' % drawn),
            Check('S2-3/one-column', one_col,
                  'and it covers exactly one text column'
                  if one_col else 'columns differing: %s'
                  % (pattern.differing_columns(pattern.row_of(got, row), plain)
                     if got else 'no dump')),
        ]


# --- S2-4  SELECTION EXTENDS AND LEAVES NOTHING BEHIND ----------------


class S24Select(S2Case):
    name = 'S2-4-select'
    desc = 'SHIFT+RIGHT inverts every column it covers, and deselect leaves none'
    origin = ('round 2: SELDIFF extends a selection ONE COLUMN at a time, so '
               'with a cell-granularity painter two consecutive deltas landed '
               'on the same cell and their XORs cancelled -- selecting 5..11 '
               'inverted only cell 2, and deselecting left cells 3 and 4 '
               'standing as residue.  The selection engine was never broken, '
               'only the painting.')
    LINES = ['SELECT SOME OF THIS LINE PLEASE', 'SECOND LINE']

    def fixture(self, ctx, variant=None):
        return crlf(self.LINES)

    def timeline(self, ctx, variant=None):
        t = Timeline()
        t.press('RIGHT', repeat=5)
        t.snap('before', vram='pat')
        t.press('RIGHT', mods=['SHIFT'], repeat=6)
        t.snap('selected', vram='pat')
        t.press('LEFT')                     # unshifted: deselect
        t.snap('after', vram='pat')
        return t

    def verify(self, ctx, runs):
        run = one(runs)
        checks = []
        plain = pattern.compose_row(font(ctx), self.LINES[0])
        row = pattern.TXRFIRST + (run.var('selected', 'CURY') or 0)
        sel = run.blob('selected', 'pat')
        after = run.blob('after', 'pat')
        if sel is None or after is None:
            return [Check('S2-4/dump', False, 'missing VRAM dump')]
        checks.append(Check('S2-4/selact',
                            run.var('selected', 'SELACT') == 1,
                            'SELACT = %s' % run.var('selected', 'SELACT')))
        inv = pattern.inverted_columns(pattern.row_of(sel, row), plain)
        # The cursor is itself an inversion and sits at one end of the range,
        # so the inverted set is the selected columns, cursor included.
        want = list(range(5, 12))
        checks.append(Check('S2-4/range', inv == want,
                            'columns %d..%d inverted' % (want[0], want[-1])
                            if inv == want else 'inverted: %s' % inv))
        # After deselecting, only the cursor cell may differ from the document.
        curx = run.var('after', 'CURX')
        diff = pattern.differing_columns(pattern.row_of(after, row), plain)
        residue = [c for c in diff if c != curx]
        checks.append(Check('S2-4/no-residue', not residue,
                            'zero columns left inverted after deselect'
                            if not residue else 'residue at %s' % residue))
        return checks


