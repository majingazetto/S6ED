CASES = [S621Render(), S622Edit(), S623Scroll(), S624HScroll(),
         S625Windows(), S626Browse(), S627DatForeign(), S628LoadProgress(),
         S629BrowseBusy(), S6210ShippedDisk()]


def run(ctx, cases=None):
    """Execute the S62 gate.  Same shape as gate.run and gate_s2.run."""
    checks = []
    for case in (cases if cases is not None else CASES):
        try:
            runs = case.execute(ctx)
        except Exception as exc:                          # noqa: BLE001
            checks.append(Check(case.name, False, 'harness error: %s' % exc))
            continue
        broken = [v for v, r in runs.items()
                  if r.timed_out or 'DONE' not in r.lines]
        if broken:
            checks.append(Check(case.name, False,
                                'session did not finish: %s'
                                % ', '.join(str(v) for v in broken)))
            continue
        try:
            checks += case.verify(ctx, runs)
        except Exception as exc:                          # noqa: BLE001
            checks.append(Check(case.name, False,
                                'verify error: %s: %s'
                                % (type(exc).__name__, exc)))
    return checks
